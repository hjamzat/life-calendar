// Generates site/lib/tz-cities.js: the reference city coordinates of every
// IANA time zone (from tzdata's zone.tab), used as the sunset location when
// the wallpaper URL has no lat/lon. Legacy names that browsers still report
// (Asia/Calcutta, Europe/Kiev, ...) map to their current zone.tab name.
//
//   node scripts/tz-cities.mjs [/usr/share/zoneinfo] > site/lib/tz-cities.js
import { readFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";

// ISO 6709 ±DDMM[SS] / ±DDDMM[SS] → decimal degrees, 2 places (~1 km)
function deg(s, w) {
  const sign = s[0] === "-" ? -1 : 1;
  const d = Number(s.slice(1, 1 + w));
  const m = Number(s.slice(1 + w, 3 + w));
  const sec = Number(s.slice(3 + w) || 0);
  return Math.round(sign * (d + m / 60 + sec / 3600) * 100) / 100;
}

const zones = {};
for (const line of readFileSync(join(dir, "zone.tab"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [, coords, tz] = line.split("\t");
  const [, lat, lon] = coords.match(/^([+-]\d+)([+-]\d+)$/);
  zones[tz] = [deg(lat, 2), deg(lon, 3)];
}

// Browsers report CLDR names, which keep some old spellings (Asia/Calcutta):
// Intl canonicalises a zone.tab name to the one the browser will report.
const aliases = {};
for (const tz of Object.keys(zones)) {
  const reported = new Intl.DateTimeFormat("en", { timeZone: tz }).resolvedOptions().timeZone;
  if (reported !== tz && !zones[reported]) aliases[reported] = tz;
}
for (const tz of Intl.supportedValuesOf("timeZone")) {
  if (!zones[tz] && !aliases[tz]) console.error(`no city for ${tz}`);
}

const out = [
  "// Generated by scripts/tz-cities.mjs from tzdata zone.tab — do not edit.",
  "// Reference city [lat, lon] of each IANA time zone.",
  "export const TZ_CITIES = {",
  ...Object.keys(zones).sort().map((tz) => `  ${JSON.stringify(tz)}: [${zones[tz].join(", ")}],`),
  "};",
  "",
  "// Legacy names some browsers report → the zone whose city to use.",
  "export const TZ_ALIASES = {",
  ...Object.keys(aliases).sort().map((tz) => `  ${JSON.stringify(tz)}: ${JSON.stringify(aliases[tz])},`),
  "};",
  "",
];
process.stdout.write(out.join("\n"));
